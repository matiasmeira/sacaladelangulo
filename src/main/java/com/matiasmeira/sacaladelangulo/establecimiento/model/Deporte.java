package com.matiasmeira.sacaladelangulo.establecimiento.model;

/**
 * Deportes soportados por una cancha. Una misma cancha puede estar habilitada
 * para más de uno (ej. fútbol y hockey) y aparecer en la búsqueda de ambos.
 */
public enum Deporte {
    FUTBOL,
    PADEL,
    TENIS,
    HOCKEY,
    BASQUET,
    VOLEY
}
